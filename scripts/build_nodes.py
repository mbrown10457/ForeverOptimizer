#!/usr/bin/env python3
"""Build ForeverOptimizer/Data/Nodes.lua from GatherLite's Forever node database.

GatherLite (https://github.com/Wuild/GatherLite, MIT, (c) 2019 Wuild) ships
plugins/database/data/forever.lua, [objectID][uiMapID] = {x, y, ...}, built by its
tools/update_forever_wowhead.py from Wowhead's Forever maps, and scripts/nodes.lua,
which groups object ids into named herb and ore nodes with their skill levels.
This script joins the two, keeps herbs and ores, merges every object id of a node,
drops points closer than MERGE (normalised) to one already kept, and writes the seed.

    python3 -I scripts/build_nodes.py <gatherlite dir> [--commit <sha>] [--date <yyyy-mm-dd>]

The GatherLite directory needs forever.lua, nodes.lua and LICENSE. Nothing is executed.
"""
import argparse
import re
import sys
from pathlib import Path

MERGE = 0.002          # ~8-12 yards on a zone map: Wowhead lists the same spawn twice at that distance
SPECIAL = {
    "khadgars_whisker": "Khadgar's Whisker", "arthas_tears": "Arthas' Tears", "fools_gold_vein": "Fool's Gold Vein",
    "ungoro_dirt_pile": "Un'Goro Dirt Pile",
}


def display(snake):
    if snake in SPECIAL:
        return SPECIAL[snake]
    return " ".join(w.capitalize() for w in snake.split("_"))


def parse_nodes(text):
    """InsertObject(kind, { ids }, "name", icon, { levels } ...) -> {objectID: (kind, name, skill)}"""
    out, names = {}, {}
    pat = re.compile(r'InsertObject\(\s*"(\w+)"\s*,\s*\{([^}]*)\}\s*,\s*"([^"]+)"\s*,\s*"[^"]*"\s*,\s*(nil|\{[^}]*\})', re.S)
    for kind, ids, name, levels in pat.findall(text):
        if kind not in ("herb", "ore"):
            continue
        skill = None
        if levels != "nil":
            nums = [int(n) for n in re.findall(r"\d+", levels)]
            skill = nums[0] if nums else None
        for oid in re.findall(r"\d+", ids):
            out[int(oid)] = (kind, display(name), skill)
        names[display(name)] = (kind, skill)
    return out, names


def parse_points(text):
    """addon.predefined = { [objectID] = { [uiMapID] = { x, y, ... } } } -> {objectID: {mapID: [(x, y), ...]}}"""
    out = {}
    obj = None
    cur_map = None
    for line in text.splitlines():
        m = re.match(r"\s{4}\[(\d+)\] = \{", line)
        if m:
            obj = int(m.group(1))
            out.setdefault(obj, {})
            continue
        m = re.match(r"\s{8}\[(\d+)\] = \{", line)
        if m and obj is not None:
            cur_map = int(m.group(1))
            out[obj].setdefault(cur_map, [])
            continue
        if obj is not None and cur_map is not None and re.match(r"\s{12}[0-9.]", line):
            nums = [float(n) for n in re.findall(r"[0-9]*\.[0-9]+|\b[01]\b", line)]
            pts = out[obj][cur_map]
            for i in range(0, len(nums) - 1, 2):
                pts.append((nums[i], nums[i + 1]))
    return out


def thin(points):
    kept = []
    for x, y in sorted(points):
        if any(abs(x - kx) < MERGE and abs(y - ky) < MERGE for kx, ky in kept[-40:]):
            continue
        kept.append((x, y))
    return kept


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("--commit", default="?")
    ap.add_argument("--date", default="?")
    ap.add_argument("--out", default="ForeverOptimizer/Data/Nodes.lua")
    a = ap.parse_args()
    src = Path(a.src)
    objects, names = parse_nodes((src / "nodes.lua").read_text())
    points = parse_points((src / "forever.lua").read_text())
    merged = {}   # name -> {mapID: set(points)}
    raw = 0
    unknown = set()
    for oid, maps in points.items():
        if oid not in objects:
            unknown.add(oid)
            continue
        kind, name, skill = objects[oid]
        for mapID, pts in maps.items():
            raw += len(pts)
            merged.setdefault(name, {}).setdefault(mapID, set()).update(pts)
    lines = []
    total = 0
    for name in sorted(merged):
        kind, skill = names[name]
        maps = merged[name]
        body = []
        for mapID in sorted(maps):
            pts = thin(maps[mapID])
            total += len(pts)
            flat = ",".join(f"{x:g},{y:g}" for x, y in pts)
            body.append(f"[{mapID}]={{{flat}}}")
        lines.append(f'do local f=function() N["{name}"]={{kind="{kind}",skill={skill if skill is not None else "nil"},maps={{{",".join(body)}}}}} end f() end')
    header = f"""-- GENERATED by scripts/build_nodes.py from GatherLite's Forever node database. Do not edit by hand.
-- Source: https://github.com/Wuild/GatherLite (MIT License, Copyright (c) 2019 Wuild; see NODES_LICENSE.txt),
-- plugins/database/data/forever.lua at {a.commit} ({a.date}), itself built from Wowhead's Forever maps
-- (https://www.wowhead.com/forever/). {total} spawn points of {len(merged)} herb and ore nodes on {len({m for v in merged.values() for m in v})} maps,
-- thinned from {raw} raw points (duplicates within {MERGE} of a kept point dropped).
-- N[name] = {{ kind = "herb"|"ore", skill = minimum skill, maps = {{ [uiMapID] = {{ x, y, x, y, ... }} }} }}, coordinates 0-1.
local ADDON, FO = ...
FO.Seed = FO.Seed or {{}}
FO.Seed.nodeSource = "GatherLite {a.commit} ({a.date}) from Wowhead Forever"
FO.Seed.nodeCount = {total}
FO.Seed.nodes = {{}}
local N = FO.Seed.nodes
"""
    Path(a.out).write_text(header + "\n".join(lines) + "\n")
    print(f"wrote {a.out}: {total} points ({raw} raw) for {len(merged)} nodes; {len(unknown)} object ids skipped (containers, fishing, unknown)")
    for name in sorted(merged):
        n = sum(len(thin(p)) for p in merged[name].values())
        print(f"  {names[name][0]:4s} {name:28s} {n:5d} points on {len(merged[name])} maps, skill {names[name][1]}")


if __name__ == "__main__":
    sys.exit(main())
