#!/usr/bin/env python3
"""Build ForeverOptimizer/Data/Items.lua from the Forever client's own item tables.

Source: wago.tools DB2 CSV exports for the `wowf` product (World of Warcraft: Forever).
  ItemSparse  -> name, sell/buy price, quality, item level, required level, stack, bonding, inventory type
  Item        -> classID, subclassID

Usage:
  scripts/build_seed.py                      # latest wowf build from the wago.tools API
  scripts/build_seed.py --build 1.60.1.70707 # a specific build
  scripts/build_seed.py --csv-dir cache/     # reuse already-downloaded ItemSparse.csv / Item.csv

Downloads are cached in --cache (default: scripts/.seedcache/<build>/). Nothing here runs in game;
the output is a plain Lua data file loaded by the addon before any module.
"""
import argparse, csv, json, os, sys, urllib.request

API_BUILDS = "https://wago.tools/api/builds"
CSV_URL = "https://wago.tools/db2/{table}/csv?build={build}"
FIELDS = ("name", "sell", "buy", "quality", "ilvl", "reqlvl", "stack", "classID", "subclassID", "bonding", "invType", "startQuest")
CHUNK = 2500  # rows per closure: keeps each Lua function's constant table far below the 5.1 limit

def fetch(url, dest):
    if os.path.exists(dest) and os.path.getsize(dest) > 0:
        return dest
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": "ForeverOptimizer-seed/1.0"})
    with urllib.request.urlopen(req, timeout=180) as r, open(dest, "wb") as f:
        f.write(r.read())
    return dest

def latest_build(product):
    with urllib.request.urlopen(urllib.request.Request(API_BUILDS, headers={"User-Agent": "ForeverOptimizer-seed/1.0"}), timeout=60) as r:
        data = json.load(r)
    builds = data.get(product) or []
    if not builds:
        sys.exit(f"product {product!r} not listed at {API_BUILDS}")
    return builds[0]["version"]

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--product", default="wowf")
    ap.add_argument("--build", help="client build, e.g. 1.60.1.70707 (default: latest for --product)")
    ap.add_argument("--csv-dir", help="directory holding ItemSparse.csv and Item.csv (skips download)")
    ap.add_argument("--cache", default=os.path.join(os.path.dirname(__file__), ".seedcache"))
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "ForeverOptimizer", "Data", "Items.lua"))
    a = ap.parse_args()

    build = a.build or (None if a.csv_dir else latest_build(a.product))
    if a.csv_dir:
        sparse_p, item_p = os.path.join(a.csv_dir, "ItemSparse.csv"), os.path.join(a.csv_dir, "Item.csv")
        build = build or "unknown"
    else:
        d = os.path.join(a.cache, build)
        sparse_p = fetch(CSV_URL.format(table="ItemSparse", build=build), os.path.join(d, "ItemSparse.csv"))
        item_p = fetch(CSV_URL.format(table="Item", build=build), os.path.join(d, "Item.csv"))

    items = {}
    with open(item_p, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            items[r["ID"]] = (int(r["ClassID"] or 0), int(r["SubclassID"] or 0))

    rows = []
    with open(sparse_p, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            name = (r.get("Display_lang") or "").strip()
            if not name:
                continue
            cls, sub = items.get(r["ID"], (0, 0))
            rows.append((int(r["ID"]), name, int(r["SellPrice"] or 0), int(r["BuyPrice"] or 0), int(r["OverallQualityID"] or 0),
                         int(r["ItemLevel"] or 0), int(r["RequiredLevel"] or 0), int(r["Stackable"] or 1), cls, sub,
                         int(r["Bonding"] or 0), int(r["InventoryType"] or 0), int(r["StartQuestID"] or 0)))
    rows.sort()

    out = [
        "-- GENERATED by scripts/build_seed.py from wago.tools DB2 exports. Do not edit by hand.",
        f"-- product {a.product}, client build {build}, {len(rows)} items",
        "-- Row layout: " + ", ".join(f"[{i+1}]={n}" for i, n in enumerate(FIELDS)),
        "local ADDON, FO = ...",
        "FO.Seed = FO.Seed or {}",
        f'FO.Seed.build = "{build}"',
        f'FO.Seed.product = "{a.product}"',
        f"FO.Seed.itemCount = {len(rows)}",
        "FO.Seed.items = {}",
        "local I = FO.Seed.items",
    ]
    for start in range(0, len(rows), CHUNK):
        out.append("do local f = function()")
        for (iid, name, sell, buy, q, ilvl, req, stack, cls, sub, bond, inv, sq) in rows[start:start + CHUNK]:
            tail = f",{sq}" if sq else ""
            out.append(f"I[{iid}]={{{lua_str(name)},{sell},{buy},{q},{ilvl},{req},{stack},{cls},{sub},{bond},{inv}{tail}}}")
        out.append("end f() end")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"{a.out}: {len(rows)} items from build {build} ({os.path.getsize(a.out)//1024} KB)", file=sys.stderr)

if __name__ == "__main__":
    main()
